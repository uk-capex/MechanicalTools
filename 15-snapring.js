      function buildSnapSelect() {
        const type = $("snap-type").value;
        const data = SNAP_DATA[type];
        $("snap-size").innerHTML = data
          .map(
            (r, i) =>
              `<option value="${i}">${r[0]} mm</option>`,
          )
          .join("");
        calcSnap();
      }
      function calcSnap() {
        const type = $("snap-type").value;
        const data = SNAP_DATA[type];
        const r = data[+$("snap-size").value];
        if (!r) return;
        const [d1, d2, t, d3, d5] = r;
        const isShaft = type === "shaft";
        const m = SNAP_M[t];
        const depth = Math.abs(d1 - d2) / 2;
        const tolD2 = snapD2Tol(isShaft, d1);
        const second = SNAP_SECOND[type].includes(d1);
        $("snap-size-label").textContent = isShaft ? "軸径" : "穴径";
        $("snap-d").innerHTML = `${d1}<span class="card-unit"> mm</span>`;
        $("snap-groove-d").innerHTML = `${d2.toFixed(2)}<span class="card-unit"> mm</span>`;
        $("snap-groove-d-tol").textContent = `公差 ${tolD2}`;
        $("snap-groove-w").innerHTML = `${m.toFixed(2)}<span class="card-unit"> mm</span>`;
        $("snap-groove-w-tol").textContent = "+0.14 / 0";
        const rows = [
          ["呼び（" + (isShaft ? "軸径" : "穴径") + "）d1", `${d1} mm`, second ? "（ ）付き＝第2選択" : "JIS B 2804 C形"],
          [isShaft ? "溝径 d2" : "溝径 d2", `${d2.toFixed(2)} mm`, `公差 ${tolD2}`],
          ["溝幅 m", `${m.toFixed(2)} mm`, "公差 +0.14 / 0"],
          ["溝深さ（参考）", `${depth.toFixed(2)} mm`, "= |d1 − d2| / 2"],
          ["止め輪 厚さ t", `${t.toFixed(1)} mm`, t === 1.6 ? "当分の間1.5可（その場合 m=1.65）" : "JIS"],
          [isShaft ? "止め輪 自由内径 d3" : "止め輪 自由外径 d3", `${d3} mm`, "JIS 基準寸法"],
          [isShaft ? "はめるときの外周最大径 d5" : "はめるときの内周最小径 d5", `${d5} mm`, "周辺の干渉確認用（約）"],
        ];
        $("snap-tbody").innerHTML = rows
          .map(
            (x) =>
              `<tr><td>${x[0]}</td><td class="hl">${x[1]}</td><td style="color:var(--muted);font-family:'Noto Sans JP',sans-serif">${x[2]}</td></tr>`,
          )
          .join("");
      }
