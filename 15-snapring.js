      function snapD2Tol(isShaft, d) {
        if (isShaft) {
          if (d <= 10) return "0 / −0.09";
          if (d <= 19) return "0 / −0.11";
          if (d <= 30) return "0 / −0.21";
          if (d <= 52) return "0 / −0.25";
          return "0 / −0.30";
        }
        if (d <= 17) return "+0.11 / 0";
        if (d <= 28) return "+0.21 / 0";
        if (d <= 47) return "+0.25 / 0";
        if (d <= 75) return "+0.30 / 0";
        return "+0.35 / 0";
      }
