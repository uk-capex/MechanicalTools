      function buildSnapSelect() {
        const type = $("snap-type").value;
        const data = SNAP_DATA[type];
        $("snap-size").innerHTML = data
          .map(
            (r, i) =>
              `<option value="${i}">${r[0]} mm</option>`,
          )
          .join("");
        calcSnap();
      }
      function calcSnap() {
        const type = $("snap-type").value;
        const data = SNAP_DATA[type];
        const r = data[+$("snap-size").value];
        if (!r) return;
        const isShaft = type === "shaft";
        $("snap-size-label").textContent = isShaft
          ? "軸径"
          : "穴径";
        $("snap-d").innerHTML =
          `${r[0]}<span class="card-unit"> mm</span>`;
        const gd_tol = isShaft ? "−0.1/0" : "+0.1/0";
        $("snap-groove-d").innerHTML =
          `${r[1].toFixed(1)}<span class="card-unit"> mm</span>`;
        $("snap-groove-d-tol").textContent =
          `公差 ${gd_tol}`;
        $("snap-groove-w").innerHTML =
          `${r[2].toFixed(1)}<span class="card-unit"> mm</span>`;
        $("snap-groove-w-tol").textContent = "+0.05/0";
        const rows = [
          [isShaft ? "軸径" : "穴径", `${r[0]} mm`, ""],
          [
            isShaft
              ? "溝径 d₁（軸外面から）"
              : "溝径 D₁（穴内面から）",
            `${r[1].toFixed(2)} mm`,
            isShaft ? "公差 −0.1/0" : "公差 +0.1/0",
          ],
          [
            "溝幅 b",
            `${r[2].toFixed(2)} mm`,
            "公差 +0.05/0",
          ],
          [
            "溝深さ t",
            `${r[3].toFixed(2)} mm`,
            "軸面からの深さ",
          ],
          ["リング板厚 s", `${r[4].toFixed(2)} mm`, "参考"],
          [
            isShaft
              ? "リング外径（自由状態）"
              : "リング内径（自由状態）",
            `${r[5].toFixed(2)} mm`,
            "参考",
          ],
          [
            "溝面取り（推奨）",
            "0.2〜0.3 mm",
            "リング装着口側",
          ],
        ];
        $("snap-tbody").innerHTML = rows
          .map(
            (x) =>
              `<tr><td>${x[0]}</td><td class="hl">${x[1]}</td><td style="color:var(--muted);font-family:'Noto Sans JP',sans-serif">${x[2]}</td></tr>`,
          )
          .join("");
      }
